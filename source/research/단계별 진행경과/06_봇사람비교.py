def self_check():
    """
    U·δ·BH 구현을 손으로 푼 고정 예제와 맞춰 본다. 하나라도 어긋나면 중단한다.

    왜 매 실행마다 보나. 04가 stanza 토큰화를 자가검증했던 것과 같은 이유다.
    순위 검정은 틀려도 조용하다 — 순위합을 하나 밀리거나, 동점 보정 항의
    부호를 뒤집거나, U를 그룹2 기준으로 잡아도 코드는 멀쩡히 돌고 그럴듯한
    p값이 나온다. 그리고 그 표를 며칠 들여다본 뒤에야 이상하다는 것을 안다.
    검정 기계 자체를 먼저 통과시키고 본 비교로 들어가는 편이 훨씬 싸다.

    ── 예제 1. 완전 분리 ─────────────────────────────────────
        A(그룹1) = [1, 2, 3],  B(그룹2) = [4, 5, 6]
        합쳐 정렬하면 1 2 3 4 5 6, 동점 없음 → 순위 1 2 3 4 5 6.
        A의 순위합 R_A = 1 + 2 + 3 = 6,  n1 = n2 = 3.
        U_A = R_A − n1(n1+1)/2 = 6 − 3·4/2 = 6 − 6 = 0
              (A가 이긴 쌍이 하나도 없다 — 실제로 A의 모든 값이 B보다 작다)
        δ   = 2·0/(3·3) − 1 = −1.0        (한쪽이 항상 진다)
        σ²  = (9/12)·[(6+1) − 0] = 0.75 × 7 = 5.25

    ── 예제 2. 동점 포함 ─────────────────────────────────────
        A(그룹1) = [1, 1, 2],  B(그룹2) = [1, 2, 2]
        합치면 1 1 1 2 2 2. 1이 자리 1·2·3을 나눠 가져 평균 순위 (1+2+3)/3 = 2,
        2가 자리 4·5·6을 나눠 가져 평균 순위 (4+5+6)/3 = 5.
        A의 값 1,1,2 → 순위 2, 2, 5.   R_A = 9.
        U_A = 9 − 3·4/2 = 9 − 6 = 3.0
        쌍별로 세어도 같다. A×B 아홉 쌍에서 A가 이기면 1, 동점이면 ½:
            (1,1)=½  (1,2)=0  (1,2)=0
            (1,1)=½  (1,2)=0  (1,2)=0
            (2,1)=1  (2,2)=½  (2,2)=½
            합 = ½+½+1+½+½ = 3.0     ← 순위합 방식과 일치
        δ   = 2·3/(3·3) − 1 = 2/3 − 1 = −1/3 ≈ −0.3333
        σ²  = 동점 묶음이 t=3 두 개 → Σ(t³−t) = 24 + 24 = 48
              (9/12)·[7 − 48/(6·5)] = 0.75 × (7 − 1.6) = 0.75 × 5.4 = 4.05
        예제 1의 5.25보다 작다 — 동점이 U가 흔들릴 폭을 좁혔기 때문이다.
        이 예제가 붙어 있는 이유가 그것이다. 보정 항을 빠뜨리면 여기서 걸린다.

    ── 예제 3. BH 보정 ───────────────────────────────────────
        p = [0.01, 0.02, 0.03, 0.04],  m = 4
        p_(i)·m/i 를 차례로 구하면
            i=1: 0.01×4/1 = 0.04    i=2: 0.02×4/2 = 0.04
            i=3: 0.03×4/3 = 0.04    i=4: 0.04×4/4 = 0.04
        네 값이 모두 같으므로 뒤에서 끌어오는 min도 전부 0.04.
            q = [0.04, 0.04, 0.04, 0.04]
        p가 넷 다 0.05 미만이었는데 q는 0.04에 나란히 붙는다. 보정이 문턱을
        어떻게 조이는지가 한눈에 보이는 자료라 골랐다.

    통과하면 True, 아니면 화면에 원인을 적고 False.
    """
    line("[자가검증] U · δ · BH 를 손으로 푼 예제와 맞춰 본다")
    ok = True

    for name, a, b, exp_u, exp_d, exp_var in SELF_CHECK_U:
        got = mann_whitney(a, b)
        marks = []
        for label, actual, expect in (("U", got["U"], exp_u),
                                      ("δ", got["델타"], exp_d),
                                      ("σ²", got["시그마제곱"], exp_var)):
            good = abs(actual - expect) <= SELF_CHECK_TOL
            ok = ok and good
            marks.append(f"{label} 기대 {expect:>8.4f} · 실제 {actual:>8.4f} "
                         f"{'통과' if good else '실패'}")
        print(f"  {name}  A={a}  B={b}")
        for m in marks:
            print(f"    {m}")
        print(f"    (참고: z = {got['z']:.4f}, 양측 p = {got['p']:.4f})")

    got_q = bh_qvalues(SELF_CHECK_BH_P)
    good = all(abs(g - e) <= SELF_CHECK_TOL
               for g, e in zip(got_q, SELF_CHECK_BH_Q))
    ok = ok and good
    print(f"  BH 보정  p={SELF_CHECK_BH_P}")
    print(f"    기대 q={SELF_CHECK_BH_Q}")
    print(f"    실제 q={[round(v, 4) for v in got_q]}  "
          f"{'통과' if good else '실패'}")

    if not ok:
        print()
        print("■ 중단 — 자가검증 실패")
        print("  검정 구현이 손계산과 어긋납니다. 본 비교를 시작하지 않습니다.")
        print("  짚어 볼 곳:")
        print("   · ranks_with_ties 의 평균 순위 — 자리 번호가 1부터인가")
        print("     (0부터 세면 순위합이 N만큼 밀린다)")
        print("   · U1 = R1 − n1(n1+1)/2 에서 n1이 그룹1의 크기가 맞는가")
        print("   · 분산의 동점 보정 항 Σ(t³−t)/(N(N−1)) 의 부호와 분모")
        print("   · bh_qvalues 의 누적 min 방향 — 큰 p부터 거꾸로 훑는가")
        print("  이 상태로 돌리면 틀린 표가 조용히 나옵니다.")
    return ok


