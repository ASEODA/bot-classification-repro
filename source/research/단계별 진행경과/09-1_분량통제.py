def check_pred1(f_cross):
    """
    예측 1 — F 머리 다섯 단어가 매칭 후에도 |δ| ≥ 0.147 을 유지하는가.

    다섯이 모두 유지해야 적중이다. 넷만 유지해도 빗나감으로 적는다. 문턱을
    "네 개 이상"으로 느슨하게 잡을 수도 있었지만, 그런 문턱은 결과를 본
    뒤에만 정할 수 있는 종류다. 사전선언에는 "머리는 유지되고"라고만 적혀
    있으니 목록 전체가 유지되는 것을 적중으로 본다.
    """
    lookup = dict(f_cross)
    items = []
    verdicts = []
    for w in HEAD_WORDS:
        c = lookup.get(w)
        if c is None or c["델타"] is None or c["앞델타"] is None:
            # 셋 중 어느 경우든 06과 09-1을 나란히 놓을 수 없다. 적중으로도
            # 빗나감으로도 치지 않고 판정불가로 남긴다.
            why = ("05 희소성표에 없는 단어" if c is None else
                   "06에 δ가 없음" if c["앞델타"] is None else "09-1에서 검정 불가")
            v = "판정불가"
            items.append({"단어": w, "06델타": None, "08델타": None,
                          "변화량": None, "판정": v, "사유": why})
        else:
            v = "유지" if (c["유지"] and not c["뒤집힘"]) else (
                "뒤집힘" if c["뒤집힘"] else "무너짐")
            items.append({"단어": w,
                          "06델타": rnd(c["앞델타"], STAT_DIGITS),
                          "08델타": rnd(c["델타"], STAT_DIGITS),
                          "변화량": rnd(c["변화량"], STAT_DIGITS),
                          "q": None if c["q"] is None else sig(c["q"]),
                          "판정": v})
        verdicts.append(v)

    if all(v == "유지" for v in verdicts):
        overall = "적중"
    elif any(v == "판정불가" for v in verdicts):
        overall = "일부 판정불가"
    else:
        overall = "빗나감"
    return {"항목": items, "판정": overall,
            "유지수": sum(1 for v in verdicts if v == "유지"),
            "대상수": len(HEAD_WORDS)}


def check_pred2(f_cross):
    """
    예측 2 — 무너진 F 단어들이 전치사에 몰려 있는가.

    ■ 판정 ■
    무너진 단어(06 주목 → 09-1 |δ| < 0.147) 중 ADP_CORE 비율이 06 주목 단어
    전체의 ADP_CORE 비율보다 높으면 적중. 편중 배수를 함께 낸다.

    ■ 왜 '무너진 쪽의 전치사 비율'이 아니라 '배수'를 보나 ■
    06 주목 94종 중 전치사가 원래 여럿이라, 무너진 목록에 전치사가 섞여 있는
    것만으로는 아무 말도 못 한다. 기준선(주목 전체의 전치사 비율) 대비 얼마나
    진해졌는지를 봐야 "전치사에 몰렸다"가 성립한다. 이상치 교차표에서 기저율
    대비 편중 배수를 쓰는 것과 같은 논리다.

    ■ 저빈도 ■
    예측 문구에는 '저빈도'가 붙어 있지만 판정에는 넣지 않았다. 무너진 쪽과
    유지한 쪽의 출현계정수 중앙값을 나란히 찍어 읽는 사람이 직접 보게 한다.
    두 조건을 AND로 걸면 어느 쪽 때문에 빗나갔는지 구분이 안 되고, 예측의
    무게는 '전치사냐'에 실려 있다.
    """
    prior = [(k, c) for k, c in f_cross if c["앞주목"]]
    fallen = [(k, c) for k, c in prior
              if c["유지"] is False and not c["뒤집힘"]]
    held = [(k, c) for k, c in prior if c["유지"] and not c["뒤집힘"]]

    def adp_share(items, pool):
        n = len(items)
        hit = sum(1 for k, _ in items if k in pool)
        return hit, (hit / n if n else None)

    core_fall_n, core_fall = adp_share(fallen, ADP_CORE)
    core_base_n, core_base = adp_share(prior, ADP_CORE)
    amb_fall_n, amb_fall = adp_share(fallen, ADP_AMBIG)
    amb_base_n, amb_base = adp_share(prior, ADP_AMBIG)

    if not fallen:
        overall = "빗나감"          # 무너진 단어가 없으면 '꼬리가 무너진다'는 성립하지 않는다
    elif core_base in (None, 0.0):
        overall = "판정불가"        # 기준선이 0이면 배수가 정의되지 않는다
    else:
        overall = "적중" if core_fall > core_base else "빗나감"

    med_fall = (statistics.median([c["출현계정수"] for _, c in fallen])
                if fallen else None)
    med_held = (statistics.median([c["출현계정수"] for _, c in held])
                if held else None)

    return {
        "무너진단어": [k for k, _ in fallen],
        "유지단어수": len(held),
        "앞주목수": len(prior),
        "전치사_핵심": {"무너진_중": core_fall_n, "무너진_비율": rnd(core_fall, 4),
                    "주목전체_중": core_base_n, "주목전체_비율": rnd(core_base, 4),
                    "편중배수": rnd(core_fall / core_base, 3)
                    if core_base else None},
        "전치사_애매": {"무너진_중": amb_fall_n, "무너진_비율": rnd(amb_fall, 4),
                    "주목전체_중": amb_base_n, "주목전체_비율": rnd(amb_base, 4)},
        "출현계정수_중앙": {"무너진": med_fall, "유지": med_held},
        "판정": overall,
    }


def check_pred3(f_sum, m_sum):
    """
    예측 3 — M 블록이 F 블록보다 덜 흔들리는가.

    가족별 평균 |Δδ|(앞 단계 주목 항목 한정)를 견준다. M < F 이면 적중.
    빗나가면 축 내부 비율 설계가 기대한 보호를 못 한 것이고, 07의 해석도
    함께 약해진다 — 보관된 07-12 사전선언 08항(현 09-1)의 예측문이 그렇게 적어 두었다.
    """
    f_mean = f_sum["평균절대변화_앞주목한정"]
    m_mean = m_sum["평균절대변화_앞주목한정"]
    if f_mean is None or m_mean is None:
        overall = "판정불가"
    else:
        overall = "적중" if m_mean < f_mean else "빗나감"
    return {"F_평균절대변화": f_mean, "M_평균절대변화": m_mean,
            "차이": None if (f_mean is None or m_mean is None)
            else round(m_mean - f_mean, STAT_DIGITS),
            "판정": overall}


def check_pred4(f_sum, u_sum):
    """
    예측 4 — UPOS가 F와 비슷하게 흔들리는가.

    |UPOS 평균 |Δδ| − F 평균 |Δδ|| ≤ SIMILAR_TOL(0.05) 이면 적중.
    이 자는 사전선언 문구에 숫자로 없어 스크립트를 쓰면서 정했고, 그 근거는
    상수 옆에 적어 두었다(주목 문턱 0.147의 약 1/3).
    """
    f_mean = f_sum["평균절대변화_앞주목한정"]
    u_mean = u_sum["평균절대변화_앞주목한정"]
    if f_mean is None or u_mean is None:
        overall = "판정불가"
        gap = None
    else:
        gap = abs(u_mean - f_mean)
        overall = "적중" if gap <= SIMILAR_TOL else "빗나감"
    return {"F_평균절대변화": f_mean, "UPOS_평균절대변화": u_mean,
            "차이_절대": None if gap is None else round(gap, STAT_DIGITS),
            "허용폭": SIMILAR_TOL, "판정": overall}


