def pack_cross(cross, base_label):
    """
    한 가족의 대조 결과를 JSON에 담을 꼴로 바꾼다. |δ| 내림차순을 유지한다.

    기준선 칸의 이름에 단계 번호를 박는다("06델타"·"07델타"). "앞델타"라고
    적으면 파일만 열었을 때 그 값이 어느 단계에서 온 것인지 알 수 없고,
    F 블록과 M 블록을 한 화면에 놓고 볼 때 특히 헷갈린다.
    """
    return {
        k: {
            f"{base_label}델타": rnd(c["앞델타"], STAT_DIGITS),
            "08델타": rnd(c["델타"], STAT_DIGITS),
            "변화량": rnd(c["변화량"], STAT_DIGITS),
            "q": None if c["q"] is None else sig(c["q"]),
            "방향": c["방향"],
            f"{base_label}주목": c["앞주목"],
            "08주목": c["주목"],
            "유지": c["유지"],
            "뒤집힘": c["뒤집힘"],
            "판정": c["판정"],
            "봇_유효n": c["봇_유효n"],
            "사람_유효n": c["사람_유효n"],
            "출현계정수": c["출현계정수"],
            "희소": c["희소"],
        }
        for k, c in cross
    }


