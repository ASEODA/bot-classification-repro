# 아래 다섯 함수(normal_cdf · ranks_with_ties · mann_whitney · bh_qvalues ·
# direction_of)는 07_형태자질비교.py 에서 한 글자도 고치지 않고 가져온 것이고,
# 07은 다시 06_봇사람비교.py 에서 가져왔다. 06에서 손계산 예제와 scipy 대조를
# 통과한 코드라 다시 짜면 잃을 것만 있다. 사전선언이 "매칭 표본에서 06과
# 동일한 절차로 δ 재계산"이라고 못 박은 것을, 같은 절차를 다시 구현하는 것이
# 아니라 같은 코드를 그대로 쓰는 것으로 지킨다.
# 상세한 유도와 주석은 06 원본에 있다 — 여기서는 요약만 남긴다.
# ════════════════════════════════════════════════════════════════════════
def normal_cdf(x):
    """
    표준정규분포의 누적확률 Φ(x). [07에서 가져옴]

    math.erf 로 Φ(x) = ½(1 + erf(x/√2)). |x|가 8을 넘으면 배정도 실수의
    바닥에 닿아 p가 0.0으로 찍힌다 — "차이가 없을 확률이 0"이 아니라 "이
    계산으로는 더 작은 값을 구분할 수 없다"는 뜻이다.
    """
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0)))


def ranks_with_ties(values):
    """
    오름차순 순위. 같은 값끼리는 자리 번호를 나눠 갖는다. [07에서 가져옴]

    평균 순위를 쓰는 덕에 Cliff's δ의 동점 ½ 규칙이 따로 코드를 쓰지 않고도
    저절로 맞는다. 09-1의 자료에서 동점은 06·07보다 더 지배적이다 — 매칭으로
    표본이 절반 이하로 줄었는데 사용률 0인 칸의 비율은 그대로이기 때문이다.

    반환: (입력 순서 그대로의 순위 리스트, 크기 2 이상인 동점 묶음 크기 목록)
    """
    n = len(values)
    order = sorted(range(n), key=lambda i: values[i])
    sv = [values[i] for i in order]
    ranks = [0.0] * n
    ties = []
    i = 0
    while i < n:
        j = i
        while j + 1 < n and sv[j + 1] == sv[i]:
            j += 1
        # order[i..j]가 같은 값이다. 이들이 차지한 자리 번호는 i+1 … j+1 이고
        # 그 평균은 ((i+1) + (j+1)) / 2 다.
        avg = (i + j + 2) / 2.0
        for k in range(i, j + 1):
            ranks[order[k]] = avg
        if j > i:
            ties.append(j - i + 1)
        i = j + 1
    return ranks, ties


def mann_whitney(group1, group2):
    """
    Mann-Whitney U 검정(양측)과 Cliff's δ. 그룹1 기준. [07에서 가져옴]

        R1  = 그룹1이 가져간 순위의 합
        U1  = R1 − n1(n1+1)/2            (그룹1이 이긴 쌍의 수, 동점은 ½)
        δ   = 2·U1/(n1·n2) − 1           (Cliff's δ, −1 … +1)
        σ²  = (n1·n2/12)·[(N+1) − Σ(t³−t)/(N(N−1))]      (동점 보정 분산)
        z   = (U1 − n1·n2/2 − c)/σ       (c = ±0.5 연속성 보정)
        p   = 2·(1 − Φ(|z|))             (양측)

    σ² ≤ 0 이면 두 무더기의 값이 전부 같다는 뜻이라 δ = 0, z = 0, p = 1.0.

    ■ 09-1에서 이 검정을 다시 걸 때 유의할 것 ■
    매칭 표본은 06·07 표본의 부분집합이므로 n이 작다. n이 작으면 정규근사
    자체가 거칠어지고 p가 커진다. 그래서 09-1의 판정은 q가 아니라 |δ| 문턱으로
    한다(보관된 07-12 사전선언의 08-3항, 현 09-1). q는 참고로 함께 저장하되, "q가 커졌다"를 곧바로
    "신호가 약해졌다"로 읽지 않는다.
    """
    n1, n2 = len(group1), len(group2)
    ranks, ties = ranks_with_ties(group1 + group2)
    r1 = sum(ranks[:n1])
    u1 = r1 - n1 * (n1 + 1) / 2.0
    n = n1 + n2

    tie_term = sum(t ** 3 - t for t in ties) / (n * (n - 1))
    var = (n1 * n2 / 12.0) * ((n + 1) - tie_term)
    if var <= 0.0:
        return {"U": u1, "z": 0.0, "p": 1.0, "델타": 0.0, "시그마제곱": 0.0}

    delta = 2.0 * u1 / (n1 * n2) - 1.0
    mid = n1 * n2 / 2.0
    if u1 > mid:
        c = 0.5
    elif u1 < mid:
        c = -0.5
    else:
        c = 0.0
    z = (u1 - mid - c) / math.sqrt(var)
    p = min(1.0, 2.0 * (1.0 - normal_cdf(abs(z))))
    return {"U": u1, "z": z, "p": p, "델타": delta, "시그마제곱": var}


def bh_qvalues(pvals):
    """
    Benjamini-Hochberg FDR 보정. [07에서 가져옴]

        p를 오름차순으로 늘어놓고,  q_(i) = min_{j ≥ i} ( p_(j) · m / j )

    뒤에서부터 최솟값을 끌고 오는 min이 q를 단조 증가로 만든다. 1.0을 넘으면
    1.0으로 자른다.

    09-1에서 이 함수는 세 번 따로 불린다 — F 172종, 형태자질 58종, UPOS 17종에
    각각 걸어야 하기 때문이다(보관된 07-12 사전선언의 08-2항, 현 09-1: "세 가족에 각각 별도로 BH 보정").
    셋을 한 가족으로 묶으면 m이 247이 되어 UPOS 17종의 문턱이 F 172종의
    사정에 따라 흔들린다. 그리고 06은 172로, 07은 58과 17로 보정했으므로,
    09-1도 같은 가족 구획을 써야 q를 나란히 놓고 볼 수 있다.
    """
    m = len(pvals)
    order = sorted(range(m), key=lambda i: pvals[i])
    q = [0.0] * m
    running = 1.0
    for rank in range(m, 0, -1):        # 가장 큰 p부터 거꾸로 훑는다
        idx = order[rank - 1]
        val = pvals[idx] * m / rank
        if val < running:               # min_{j ≥ i} 를 누적으로 구현
            running = val
        q[idx] = min(1.0, running)
    return q


def direction_of(delta):
    """δ의 부호를 말로 옮긴다. [07에서 가져옴] 그룹1 = 봇으로 고정되어야 뜻이 맞다."""
    if delta > 0:
        return "봇이 높음"
    if delta < 0:
        return "봇이 낮음"
    return "차이 없음"


