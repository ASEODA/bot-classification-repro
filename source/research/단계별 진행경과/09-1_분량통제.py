def label_split(uids, labels):
    """계정 목록을 라벨별로 세고 비율을 낸다. 교차표의 한 줄이 된다."""
    nb = sum(1 for u in uids if labels.get(u) == GROUP1)
    nh = sum(1 for u in uids if labels.get(u) == GROUP2)
    n = nb + nh
    return {"계정수": len(uids), "라벨확인": n, "봇": nb, "사람": nh,
            "봇비율": (nb / n) if n else None}


def print_cross_row(label, stat, base_rate, n_bot_all, n_hum_all):
    """
    교차표 한 줄. 편중 배수를 함께 찍는다.

    편중 배수 = (이 무더기의 봇 비율) ÷ (전체 봇 비율).
    1.0이면 라벨과 무관하게 섞여 있다는 뜻이고, 2.0이면 봇이 두 배로 몰려
    있다는 뜻이며, 0.5면 사람 쪽으로 몰려 있다는 뜻이다. 원비율만 찍으면
    "34.6%가 봇"이 많은 건지 적은 건지 읽는 사람이 매번 암산해야 한다.
    """
    if stat["라벨확인"] == 0:
        print(f"        {label:<14}{stat['계정수']:>6,}   (라벨 확인 0)")
        return None
    ratio = stat["봇비율"] / base_rate if base_rate else None
    in_bot = stat["봇"] / n_bot_all if n_bot_all else 0.0
    in_hum = stat["사람"] / n_hum_all if n_hum_all else 0.0
    print(f"        {label:<14}{stat['계정수']:>6,}{stat['봇']:>6,}"
          f"{stat['사람']:>7,}{stat['봇비율']:>9.1%}{ratio:>8.2f}배"
          f"{in_bot:>7.1%}{in_hum:>8.1%}")
    return ratio


