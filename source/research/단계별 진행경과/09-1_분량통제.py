def sig(x, digits=SIG_DIGITS):
    """
    p·q를 유효숫자 기준으로 자른다. [07에서 가져옴]

    소수 자릿수로 반올림하면(round(p, 6)) 3e-40 같은 값이 통째로 0이 된다.
    유효숫자로 자르면 크기를 잃지 않으면서 파일이 짧아진다.
    """
    if x == 0.0:
        return 0.0
    return float(f"{x:.{digits}g}")


def rnd(x, digits):
    """None을 그대로 통과시키는 round. [07에서 가져옴] 검정 불가 칸이 None이라 필요하다."""
    return None if x is None else round(x, digits)


def quartiles(values):
    """
    중앙값과 사분위수 한 벌. [06에서 가져옴] 값이 둘 미만이면 사분위가 성립하지 않는다.

    09-1에서는 분모 분포를 매칭 전후로 견주는 데 쓴다. 중앙값 하나만으로는
    "가운데가 붙었지만 꼬리는 그대로"인 경우를 못 잡아서, 다섯 숫자를 다 찍는다.
    """
    if len(values) < 2:
        m = values[0] if values else 0.0
        return {"Q1": m, "중앙": m, "Q3": m}
    # method="inclusive"는 가진 자료가 모집단 전체일 때 쓰는 정의다(05·06과 같다).
    q1, med, q3 = statistics.quantiles(sorted(values), n=4, method="inclusive")
    return {"Q1": q1, "중앙": med, "Q3": q3}


def five_number(values):
    """최소·Q1·중앙·Q3·최대 한 벌. 매칭이 실제로 겹쳤는지를 보이는 표의 한 줄."""
    if not values:
        return {"n": 0, "최소": None, "Q1": None, "중앙": None,
                "Q3": None, "최대": None}
    q = quartiles(values)
    return {"n": len(values), "최소": min(values), "Q1": q["Q1"],
            "중앙": q["중앙"], "Q3": q["Q3"], "최대": max(values)}


