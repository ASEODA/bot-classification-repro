# [2] 캘리퍼 매칭 — 이 파일이 새로 들이는 유일한 기계
# ════════════════════════════════════════════════════════════════════════
def caliper_match(bot_ids, human_ids, logd, caliper, seed):
    """
    log 분모 차 ±caliper 이내로 봇:사람 1:1 그리디 매칭. 보관된 07-12 사전선언의 08-1항(현 09-1).

    ■ 절차 ■
      1. 봇 목록을 시드 고정 난수로 섞는다.
      2. 섞인 순서대로 봇을 하나씩 꺼내, 아직 안 쓰인 사람 중에서
         |log(봇 분모) − log(사람 분모)| ≤ caliper 인 후보를 모은다.
      3. 후보 중 가장 가까운 사람을 짝으로 삼고 그 사람을 '쓴 것'으로 표시한다.
      4. 후보가 없으면 그 봇은 탈락한다. 캘리퍼를 넓히지 않는다.

    ■ 왜 섞나 ■
    그리디는 순서에 민감하다. 먼저 온 봇이 가까운 사람을 집어 가면 나중에 온
    봇은 덜 가까운 짝을 받거나 짝을 못 받는다. 안 섞으면 uid 사전순이 곧
    매칭 우선순위가 되어, 우연히 uid가 앞쪽인 계정들이 체계적으로 유리해진다.
    섞되 시드를 박아 두면 편향은 없애고 재현성은 남는다.

    ■ 동점 처리 ■
    거리가 똑같은 후보가 둘이면 human_ids 목록의 앞쪽이 이긴다(엄격 부등호
    '<' 로 갱신하므로). human_ids 를 정렬된 상태로 넘기면 결과가 결정적이다.

    ■ 캘리퍼를 넓히지 않는 이유 ■
    "짝을 못 찾았으니 0.15까지 늘려 보자"는 순간 새 자유도가 생긴다. 어떤 폭이
    가장 좋은 결과를 내는지 여러 번 돌려 보고 고를 수 있게 되기 때문이다.
    사전선언에 ±0.10 이 적혀 있으므로 그 값만 쓰고, 못 채운 봇은 탈락시켜
    그 수를 그대로 보고한다(보관된 07-12 사전선언의 08-5항, 현 09-1: 탈락 계정은 기록만).

    반환: (쌍 목록 [(봇, 사람, 거리)…], 탈락 봇 목록, 쓰인 사람 집합)
    """
    rng = random.Random(seed)
    order = list(bot_ids)
    rng.shuffle(order)

    used = set()
    pairs = []
    unmatched_bots = []
    for b in order:
        lb = logd[b]
        best, best_gap = None, None
        for h in human_ids:
            if h in used:
                continue
            gap = abs(logd[h] - lb)
            if gap > caliper:
                continue
            if best_gap is None or gap < best_gap:
                best, best_gap = h, gap
        if best is None:
            unmatched_bots.append(b)
        else:
            used.add(best)
            pairs.append((b, best, best_gap))
    return pairs, unmatched_bots, used


