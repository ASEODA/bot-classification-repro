# [F 블록] 06의 단어 비교를 매칭 표본에 그대로 다시 건다
# ════════════════════════════════════════════════════════════════════════
def word_vector(uids, rates, word):
    """
    한 단어에 대해, 주어진 계정들의 사용률을 순서대로 늘어놓는다. [06에서 가져옴]

    ■ 여기가 F 블록에서 가장 틀리기 쉬운 한 줄이다. ■
    05는 사용률을 '희소 저장'했다 — 한 번도 안 쓴 단어는 그 계정의 "사용률"
    사전에 아예 키가 없다. 04부터 이어온 방식이고, 172종을 계정마다 다 적으면
    대부분이 0인 표가 되기 때문이다.

    그래서 .get(word, 0.0) 의 기본값 0.0이 반드시 있어야 한다. 없는 키를
    건너뛰면 "그 단어를 한 번도 안 쓴 계정"이 통째로 표본에서 사라진다.
    그러면 무더기 크기가 단어마다 제멋대로 달라지고, 남은 것은 그 단어를 쓴
    계정들끼리의 비교가 된다. 정작 재려던 것 — "봇이 이 단어를 덜 쓴다" —
    의 '덜 쓴다'가 바로 그 사라진 0들이다. 결과 전체가 뒤집힌다.

    09-1에서는 이 0들이 더 중요하다. 이 파일이 시험하려는 가설이 바로 "그
    0들의 분포가 문체가 아니라 분모 때문에 생겼다"이기 때문이다. 0을 빠뜨리면
    시험 대상 자체가 사라진다.
    """
    return [rates[u]["사용률"].get(word, 0.0) for u in uids]


def compare_words(words, bot_ids, human_ids, rates, presence):
    """
    단어를 하나씩 비교하고 p값에 BH 보정을 건다. [06에서 가져옴 — compare_words]

    06 원본과 다른 것은 넘겨받는 계정 목록뿐이다. 06은 라벨이 붙은 1,869계정
    전부를 넘겼고, 09-1은 캘리퍼 매칭을 통과한 쌍만 넘긴다. 코드가 같아야
    Δδ가 '표본이 바뀐 효과'로만 읽힌다.

    반환은 |δ| 내림차순으로 정렬된 (단어, 결과) 목록이다.
    """
    rows = []
    for w in words:
        v1 = word_vector(bot_ids, rates, w)      # ← 없는 키는 0.0으로 채워진다
        v2 = word_vector(human_ids, rates, w)
        r = mann_whitney(v1, v2)
        r["방향"] = direction_of(r["델타"])
        r["봇_중앙"] = statistics.median(v1)
        r["사람_중앙"] = statistics.median(v2)
        r["출현계정수"] = presence.get(w, 0)
        # 아래 세 칸은 06 원본에 없던 것을 09-1에서 덧붙였다. M 블록과 같은
        # 꼴로 대조 표에 담기 위해서다. 계산에는 관여하지 않는다.
        r["검정가능"] = True                     # F 블록에는 결측이 없다(0.0으로 채운다)
        r["봇_유효n"] = len(v1)
        r["사람_유효n"] = len(v2)
        rows.append((w, r))

    qs = bh_qvalues([r["p"] for _, r in rows])
    for (w, r), q in zip(rows, qs):
        r["q"] = q
        r["유의"] = q <= Q_ALPHA
        r["주목"] = r["유의"] and abs(r["델타"]) >= DELTA_NOTABLE

    rows.sort(key=lambda kv: -abs(kv[1]["델타"]))
    return rows


def word_presence(uids, rates, words):
    """매칭 표본 안에서 각 단어를 한 번이라도 쓴 계정 수. '희소' 표시의 근거."""
    out = {w: 0 for w in words}
    for u in uids:
        used = rates[u]["사용률"]
        for w in words:
            if used.get(w, 0.0) > 0:
                out[w] += 1
    return out


