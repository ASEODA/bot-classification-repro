# [대조] 09-1 결과에 앞 단계 결과를 붙인다
# ════════════════════════════════════════════════════════════════════════
def crosswalk(rows, baseline):
    """
    09-1의 한 가족 결과에 앞 단계(06 또는 07)의 δ를 나란히 붙인다.

    ■ 각 칸의 뜻 ■
        앞델타   06 또는 07이 전체 표본에서 낸 δ
        델타     09-1이 매칭 표본에서 낸 δ
        변화량   09-1 − 앞 (부호 있는 값. 방향까지 읽으려면 부호가 필요하다)
        앞주목   앞 단계에서 q ≤ 0.05 이면서 |δ| ≥ 0.147 이었는가
        주목     09-1에서 같은 두 조건을 넘었는가
        유지     09-1에서 |δ| ≥ 0.147 인가 (보관된 07-12 사전선언 08-3항의 판정 항목, 현 09-1)
        뒤집힘   부호가 반대로 갔는가

    ■ 유지와 주목을 왜 따로 두나 ■
    보관된 07-12 사전선언의 08-3항(현 09-1)이 "매칭 후에도 |δ| ≥ 0.147 을 유지하는 수"라고만 적었지
    q 조건을 붙이지 않았다. 붙이면 안 되는 이유가 있다 — 매칭으로 표본이
    절반 이하로 줄어 q는 그것만으로도 커진다. q까지 걸면 '표본이 작아진 것'을
    '신호가 사라진 것'으로 오독하게 된다. 그래서 판정은 δ 문턱으로 하고,
    q는 참고 칸으로 나란히 둔다. 09-1에서 새로 문턱을 넘은 항목(신규)도
    같은 이유로 결론에 올리지 않는다 — 09-1은 진단이지 발견이 아니다.

    ■ 뒤집힘의 무게 ■
    부호가 반대로 간 항목은 |δ|가 커도 살아남은 것이 아니다. 앞 단계에서
    "봇이 높다"였던 것이 "봇이 낮다"가 되었다면 그 항목에 대해 우리가 아는
    것은 아무것도 없다. 보관된 07-12 사전선언의 08-3항(현 09-1)은 뒤집힘이 하나라도 있으면 그 항목을
    결론에서 빼라고 적었다. 그래서 판정 칸에서 뒤집힘을 가장 먼저 찍는다.

    다만 판정 칸의 '뒤집힘'은 앞 단계나 09-1 중 한 번이라도 주목이었던 항목에만
    붙인다. δ가 +0.01에서 −0.02로 간 것도 부호로는 반전이지만, 그 항목에
    대해서는 애초에 아무 방향도 주장한 적이 없어 반전이라 부를 것이 없다.
    양쪽 다 무주목인 항목까지 뒤집힘으로 세면 가족마다 수십 종이 잡혀
    정작 중요한 반전이 그 안에 묻힌다. 원자료인 "뒤집힘" 칸은 부호 반전
    사실 그대로 True/False를 담고, "판정" 칸이 그 사실을 읽어 준다.
    """
    out = []
    for k, r in rows:
        b = baseline.get(k) or {}
        d_old = b.get("델타")
        prior_notable = bool(b.get("주목"))
        d_new = r["델타"] if r["검정가능"] else None

        if d_old is None or d_new is None:
            change = None
            flip = None
            hold = None
            verdict = "검정불가"
        else:
            change = d_new - d_old
            flip = (d_old > 0 > d_new) or (d_old < 0 < d_new)
            hold = abs(d_new) >= DELTA_NOTABLE
            if flip and (prior_notable or r["주목"]):
                verdict = "뒤집힘"
            elif prior_notable:
                verdict = "유지" if hold else "무너짐"
            elif r["주목"]:
                verdict = "신규"
            else:
                verdict = "미주목"

        out.append((k, {
            "앞델타": d_old,
            "델타": d_new,
            "변화량": change,
            "q": r.get("q"),
            "방향": r.get("방향"),
            "앞주목": prior_notable,
            "주목": bool(r.get("주목")),
            "유지": hold,
            "뒤집힘": flip,
            "판정": verdict,
            "봇_유효n": r.get("봇_유효n"),
            "사람_유효n": r.get("사람_유효n"),
            "출현계정수": r.get("출현계정수"),
            "희소": bool(r.get("희소")),
        }))
    return out


