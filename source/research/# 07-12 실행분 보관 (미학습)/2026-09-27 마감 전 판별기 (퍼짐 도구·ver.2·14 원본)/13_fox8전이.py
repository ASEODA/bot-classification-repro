def build_features(acc, order, axis_map):
    """
    반환: uids · X (계정 × 250, 결측 NaN) · 가족별 비율 사전(07 compare_family 입력).
    F는 05 규칙(6자리 반올림 사용률), M은 07 규칙, R은 08 규칙이다(10 결정 F와 같음).
    """
    uids = sorted(acc)
    fw = [k for b, k in order if b == "F"]
    mk = [k for b, k in order if b == "M형태"]
    uk = [k for b, k in order if b == "M품사"]
    rates, undefined = compute_rates(acc)
    if undefined:
        stop(f"분모(토큰수_구두점제외)가 0인 계정 {undefined[:5]}")
    fr = {u: {w: rates[u]["사용률"].get(w, 0.0) for w in fw} for u in uids}
    mr, _, _ = compute_ratios(acc, mk, axis_map)
    ur, _ = compute_upos_ratios(acc, uk)
    rr = compute_features(acc)
    ratios = {"F": fr, "형태자질": mr, "UPOS": ur, "R": rr}
    src = {"F": fr, "M형태": mr, "M품사": ur, "R": rr}
    X = np.array([[NAN if src[b][u][k] is None else src[b][u][k] for b, k in order]
                  for u in uids], dtype=float)
    return uids, X, ratios


