def gate_adapt_leak(c_res):
    """
    문턱 적응이 평가 겹의 라벨을 쓰지 않는가. 겹 f의 평가 라벨을 (가) 모두 뒤집고 (나) 무작위로
    섞어도 겹 f의 문턱과 학습 균형정확도가 비트 단위로 같아야 한다. 대조: 학습 겹 라벨을 뒤집으면
    적어도 한 겹의 문턱이 바뀌어야 한다(관문이 헛돌지 않음).
    """
    y, fold_of = c_res["_y"], c_res["_fold_of"]
    rng = np.random.default_rng([SEED, 13])
    res, ok = {}, True
    for det, sc in c_res["_scores"].items():
        for tool in TOOLS:
            s = sc[tool]
            base = adapt_thresholds(s, y, fold_of)
            same, teeth = [], []
            for f in range(N_FOLDS_ADAPT):
                te = fold_of == f
                y1 = y.copy()
                y1[te] = 1 - y1[te]
                y2 = y.copy()
                y2[te] = rng.permutation(y2[te])
                same.append(adapt_thresholds(s, y1, fold_of)[f] == base[f]
                            and adapt_thresholds(s, y2, fold_of)[f] == base[f])
                y3 = y.copy()
                y3[~te] = 1 - y3[~te]
                teeth.append(adapt_thresholds(s, y3, fold_of)[f] != base[f])
            res[f"{det}|{tool}"] = {"평가겹_라벨교란_불변": all(same), "대조_학습겹뒤집기_변함": any(teeth)}
            ok &= all(same) and any(teeth)
    n_ok = sum(v["평가겹_라벨교란_불변"] for v in res.values())
    n_teeth = sum(v["대조_학습겹뒤집기_변함"] for v in res.values())
    say(f"      평가 겹 라벨을 뒤집거나 섞어도 문턱 불변: {n_ok}/{len(res)} · 대조(학습 겹 뒤집기) 문턱 변함: "
        f"{n_teeth}/{len(res)} → {'통과' if ok else '■ 실패'}")
    return res, bool(ok)


def gate_determinism(uids, X, order, acc, labels, bundles, b_res, c_res, n_boot):
    """같은 프로세스에서 매칭 · (b) F 거리 · 두 번들 점수 · 부트스트랩 AUC 하나를 다시 계산한다(D22)."""
    res = {}
    pairs, _, _, _, _ = match_fox8(uids, acc, labels)
    res["매칭쌍"] = [[b, h, g] for b, h, g in pairs] == b_res["매칭"]["쌍"]
    ids, XB, _ = b_block_arrays(uids, X, order, pairs)
    n = len(pairs)
    d = b_distances(XB["F"], np.array([True] * n + [False] * n))["d"]
    res["(b)_F_거리"] = (list(map(float, d[:n])) == list(b_res["블록별"]["F"]["계정별_거리"]["봇"].values())
                       and list(map(float, d[n:])) == list(b_res["블록별"]["F"]["계정별_거리"]["사람"].values()))
    same_sc = True
    for det, (b, w) in bundles.items():
        sc, _, _, _ = apply_detector(b, w, X)
        same_sc &= all(np.array_equal(sc[t], c_res["_scores"][det][t]) for t in TOOLS)
    res["두번들_점수"] = bool(same_sc)
    y = c_res["_y"]
    bidx, hidx = np.where(y == 1)[0], np.where(y == 0)[0]
    Wh = boot_counts(BOOT_KEY["사람"], [0] * len(hidx), n_boot)
    Wb = boot_counts(BOOT_KEY["주_봇"], [0] * len(bidx), n_boot)
    _, dd = auc_boot(c_res["_scores"][DET_V1][ROW_PROP], bidx, hidx, Wb, Wh)
    res["부트스트랩_ver1제안"] = bool(np.array_equal(dd, c_res["_dist"][(DET_V1, ROW_PROP)]))
    for k, v in res.items():
        say(f"      {k:<22} {'같음' if v else '■ 다름'}")
    return res, all(res.values())


