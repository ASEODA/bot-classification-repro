def gate_hand():
    """
    6계정(3쌍) × 3자질 손 예제. 파일 위 상수 주석에 손계산 과정이 있다.
    본 계산과 같은 함수(centers·residuals·residual_scale·scaled_residuals·
    block_distances·ratio_of·perm_ratios·p_values)를 그대로 부른다. 손 예제용
    별도 구현을 두지 않는다.
    (v1.3) 척도의 대체·제외 가지는 따로 만든 잔차로 본다. 끝에 이동 불변 관문을
    둔다. 한 집단 원값에 상수를 더해도 잔차가 같으므로 거리·비율·p가 그대로여야
    한다. 폭을 바꾸는 대조(봇 ×2)도 함께 돌려, 관문이 헛돌지 않음을 보인다.
    """
    feats = ["a", "b", "c"]
    X = np.array([[np.nan if HAND_VALUES[f][u] is None else HAND_VALUES[f][u]
                   for f in feats] for u in HAND_IDS], dtype=float)
    is_bot = np.array([u.startswith("B") for u in HAND_IDS])
    fails = []

    # ① 집단 중심
    cb, ch = centers(X, is_bot)
    for j, f in enumerate(feats):
        if not close(cb[j], HAND_CENTER_BOT[f]):
            fails.append(f"봇 중심 {f}: {cb[j]}")
        if not close(ch[j], HAND_CENTER_HUMAN[f]):
            fails.append(f"사람 중심 {f}: {ch[j]}")
    say(f"      ① 중심 6개 (원값 중앙 봇 4/10/.3125 · 사람 6/30/.75)  "
        f"{'통과' if not fails else '실패'}")

    # ② 잔차
    R = residuals(X, is_bot, cb, ch)
    n0 = len(fails)
    for i, u in enumerate(HAND_IDS):
        for j, f in enumerate(feats):
            if not close(R[i, j], HAND_RESID[f][u]):
                fails.append(f"잔차 {u}.{f}: {R[i, j]} ≠ {HAND_RESID[f][u]}")
    say(f"      ② 잔차 18칸 (c 결측 포함)  {'통과' if len(fails) == n0 else '실패'}")

    # ③ 척도
    s, kind = residual_scale(R)
    n0 = len(fails)
    for j, f in enumerate(feats):
        if not close(s[j], HAND_SCALE[f]) or kind[j] != "중앙값":
            fails.append(f"척도 {f}: {s[j]} ({kind[j]}) ≠ {HAND_SCALE[f]} (중앙값)")
    say(f"      ③ 척도 3개 (1 · 5 · .1875, 모두 중앙값)  {'통과' if len(fails) == n0 else '실패'}")

    # ④ z (상한)
    Z = scaled_residuals(R, s)
    n0 = len(fails)
    for i, u in enumerate(HAND_IDS):
        for j, f in enumerate(feats):
            if not close(Z[i, j], HAND_Z[f][u]):
                fails.append(f"z {u}.{f}: {Z[i, j]} ≠ {HAND_Z[f][u]}")
    with np.errstate(invalid="ignore"):
        capped = int(np.sum(np.abs(R) / s[None, :] > CAP))
    if capped != HAND_CAP_CELLS:
        fails.append(f"상한 넘은 칸 {capped} ≠ {HAND_CAP_CELLS}")
    say(f"      ④ z 18칸 (H1.a 6 → 상한 5, 상한 넘은 칸 {capped})  "
        f"{'통과' if len(fails) == n0 else '실패'}")

    # ⑤ 거리
    d, used = block_distances(Z)
    n0 = len(fails)
    for i, u in enumerate(HAND_IDS):
        if not close(d[i], HAND_DIST[u]):
            fails.append(f"거리 {u}: {d[i]} ≠ {HAND_DIST[u]}")
    if list(used) != [3, 3, 2, 3, 3, 3]:
        fails.append(f"사용 자질 수 {list(used)} ≠ [3,3,2,3,3,3]")
    say(f"      ⑤ 거리 6개 (B3는 결측 빼고 2자질 평균)  "
        f"{'통과' if len(fails) == n0 else '실패'}")

    idx = {u: i for i, u in enumerate(HAND_IDS)}
    d_bot = np.array([d[idx[b]] for b, _ in HAND_PAIRS])
    d_hum = np.array([d[idx[h]] for _, h in HAND_PAIRS])
    obs = ratio_of(d_bot, d_hum)
    n0 = len(fails)
    if not close(obs, HAND_RATIO):
        fails.append(f"관측 비율 {obs} ≠ 17/6")
    say(f"      관측 비율 = 17/6 = {HAND_RATIO:.6f}  계산 {obs:.6f}  "
        f"{'통과' if len(fails) == n0 else '실패'}")

    # ⑥ 교환 8가지와 p
    keys = list(HAND_SWAPS)
    swaps = np.array(keys, dtype=bool)
    got = perm_ratios(d_bot, d_hum, swaps)
    n0 = len(fails)
    for k, g in zip(keys, got):
        if not close(g, HAND_SWAPS[k]):
            fails.append(f"교환 {k}: {g} ≠ {HAND_SWAPS[k]}")
    say(f"      ⑥ 교환 8가지 비율 전부                  "
        f"{'통과' if len(fails) == n0 else '실패'}")
    for k, g in zip(keys, got):
        say(f"        {''.join(map(str, k))}  {g:.6f}  (손계산 {HAND_SWAPS[k]:.6f})")

    e1, e2 = exact_p(obs, got)
    f1, f2, _, _ = p_values(obs, got)
    n0 = len(fails)
    for nm, a, b in (("정확 단측", e1, HAND_EXACT_P1), ("정확 양측", e2, HAND_EXACT_P2),
                     ("공식 단측", f1, HAND_FORMULA_P1), ("공식 양측", f2, HAND_FORMULA_P2)):
        if not close(a, b):
            fails.append(f"{nm} p {a} ≠ {b}")
    say(f"      p: 정확 단측 {e1:.4f}(2/8) · 양측 {e2:.4f}(4/8) · "
        f"공식 {f1:.4f}(3/9) · {f2:.4f}(5/9)  "
        f"{'통과' if len(fails) == n0 else '실패'}")

    # 무작위 교환 10,000회를 같은 예제에 걸어 정확 p 근처로 오는지 본다.
    # 손계산 상수가 아니라 난수 경로 점검이다(표준오차 약 0.004).
    rng = np.random.default_rng(SEED)
    mc = perm_ratios(d_bot, d_hum, rng.random((N_PERM, 3)) < 0.5)
    m1, m2, _, _ = p_values(obs, mc)
    n0 = len(fails)
    if abs(m1 - HAND_EXACT_P1) > HAND_MC_TOL or abs(m2 - HAND_EXACT_P2) > HAND_MC_TOL:
        fails.append(f"무작위 p {m1:.4f}/{m2:.4f}가 정확 p에서 {HAND_MC_TOL} 넘게 벗어남")
    say(f"      무작위 교환 10,000회: 단측 {m1:.4f} · 양측 {m2:.4f} "
        f"(허용차 ±{HAND_MC_TOL})  {'통과' if len(fails) == n0 else '실패'}")

    # ⑦ 척도 대체·제외 가지 (따로 만든 잔차)
    T = np.array([[np.nan if v is None else v for v in row] for row in HAND_SCALE_TEST], dtype=float)
    sT, kT = residual_scale(T)
    ZT = scaled_residuals(T, sT)
    n0 = len(fails)
    if kT != HAND_SCALE_TEST_KIND or not close(sT[0], 1.0) or not np.isnan(sT[1:]).all():
        fails.append(f"척도 대체·제외 {list(map(fnum, sT))} {kT} ≠ [1, 결측, 결측] {HAND_SCALE_TEST_KIND}")
    if not all(close(z, e) for z, e in zip(ZT[:, 0], HAND_SCALE_TEST_Z0)) or not np.isnan(ZT[:, 1:]).all():
        fails.append(f"척도 대체·제외 z {ZT.tolist()}")
    say(f"      ⑦ 척도 대체·제외 (열1 평균 1로 대체 · 열2 전부 0 제외 · 열3 정의 1개 제외)  "
        f"{'통과' if len(fails) == n0 else '실패'}")

    # ⑧ 이동 불변 (v1.3 관문). 원값에 더한 뒤 hand_run으로 처음부터 다시 돈다.
    base = hand_run(X, is_bot, swaps)
    shifted = {
        "봇 전 자질 +7.25": X + np.where(is_bot[:, None], HAND_SHIFT_BOT, 0.0),
        "사람 자질별 a −3.5 · b +7.25 · c +100.125": X + np.where(
            (~is_bot)[:, None], np.array([HAND_SHIFT_HUMAN[f] for f in feats])[None, :], 0.0),
    }
    inv = {}
    for name, Xs in shifted.items():
        dd, o, g, ps = hand_run(Xs, is_bot, swaps)
        diffs = ([abs(x - y) for x, y in zip(dd, base[0])] + [abs(o - base[1])]
                 + [abs(x - y) for x, y in zip(g, base[2])] + [abs(x - y) for x, y in zip(ps, base[3])])
        dmax = float(max(diffs))
        ok = bool(dmax <= INVAR_TOL)
        if not ok:
            fails.append(f"이동 불변 {name}: 최대차 {dmax:.2e}")
        inv[name] = {"비율": o, "최대차(거리6·비율·교환8·p4)": dmax, "통과": ok}
        say(f"      ⑧ 이동 불변 : {name}  비율 {o:.6f} · 거리·비율·p 최대차 {dmax:.1e}  "
            f"{'통과' if ok else '실패'}")
    # 대조 : 봇 원값 ×2는 폭 변화라 비율이 17/6 → 13/7로 바뀌어야 한다.
    wide = hand_run(X * np.where(is_bot[:, None], HAND_WIDEN_BOT, 1.0), is_bot, swaps)[1]
    teeth = close(wide, HAND_WIDEN_RATIO)
    if not teeth:
        fails.append(f"대조(봇 ×2) 비율 {wide} ≠ 13/7")
    inv["대조_봇x2(폭 변화)"] = {"비율": wide, "기대": HAND_WIDEN_RATIO, "통과": teeth}
    say(f"      ⑧ 대조 (폭 변화) 봇 원값 ×2 : 비율 {obs:.6f}(17/6) → {wide:.6f}(13/7)  "
        f"{'통과' if teeth else '실패'}")

    result = {
        "값": HAND_VALUES, "쌍": HAND_PAIRS,
        "기대_중심_봇": HAND_CENTER_BOT, "기대_중심_사람": HAND_CENTER_HUMAN,
        "기대_잔차": HAND_RESID, "기대_척도": HAND_SCALE, "기대_z": HAND_Z,
        "상한": CAP, "상한_넘은_칸": capped, "기대_거리": HAND_DIST,
        "기대_비율": HAND_RATIO,
        "교환8가지": [{"교환": "".join(map(str, k)), "기대": HAND_SWAPS[k],
                    "계산": float(g)} for k, g in zip(keys, got)],
        "정확p": {"단측": e1, "양측": e2}, "공식p_8가지": {"단측": f1, "양측": f2},
        "무작위10000_p": {"단측": m1, "양측": m2},
        "척도_대체제외": {"s": [fnum(v) for v in sT], "종류": kT},
        "이동불변": inv,
        "실패": fails, "통과": not fails,
    }
    return result, not fails


