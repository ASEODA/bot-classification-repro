def judge_claim(res):
    sig = [b for b in BLOCKS if res[b]["p_단측"] < ALPHA]
    if len(sig) == 3:
        row, sentence = "F·M·R 모두", CLAIM_TABLE["F·M·R 모두"]
    elif set(sig) == {"F", "M"}:
        row, sentence = "F·M", CLAIM_TABLE["F·M"]
    elif len(sig) == 1:
        row = "하나만"
        sentence = f"{CLAIM_TABLE['하나만']} (해당 층위: {sig[0]} {LAYER[sig[0]]})"
    elif not sig:
        row, sentence = "없음", CLAIM_TABLE["없음"]
    else:
        row, sentence = "사전표 미정의 조합", None      # 결정 K
    return {"p<0.05_블록": sig, "해당_행": row, "논문_문장": sentence,
            "일관된_사용가능": len(sig) == 3,
            "표": [{"블록": b, "비율": res[b]["비율"], "p_단측": res[b]["p_단측"],
                   "p_양측": res[b]["p_양측"]} for b in BLOCKS],
            "약함_판정": "사전선언에 수치 문턱이 없어 자동 판정하지 않음(결정 K). 비율로 읽는다."}


