def transfer_family(rows, base, with_items=True):
    """옛 12 pair_with_baseline · correlation_block의 정의(D4 · D5)."""
    items, xs, ys = {}, [], []
    track = Counter()
    for k, r in rows:
        b = base.get(k) or {}
        d_old = b.get("델타")
        d_new = r["델타"] if r["검정가능"] else None
        if d_old is None or d_new is None or d_old == 0.0 or d_new == 0.0:
            same = None
        else:
            same = (d_old > 0) == (d_new > 0)
        if d_new is None:
            tr = "검정불가"
        elif same is None:
            tr = "방향 없음"
        elif not same:
            tr = "역방향"
        elif abs(d_new) >= DELTA_NOTABLE:
            tr = "유지"
        else:
            tr = "약화"
        if b.get("주목"):
            track[tr] += 1
        if d_old is not None and d_new is not None:
            xs.append(d_old)
            ys.append(round(d_new, STAT_DIGITS))
        if with_items:
            items[k] = {**{kk: (fnum(v) if isinstance(v, (int, float)) and not isinstance(v, bool) else v)
                           for kk, v in r.items()},
                        "BotSim델타": d_old, "BotSim주목": bool(b.get("주목")), "부호일치": same, "추적": tr}
    rho = spearman(xs, ys)
    zero = sum(1 for x, y in zip(xs, ys) if x == 0.0 or y == 0.0)
    agree = sum(1 for x, y in zip(xs, ys) if x != 0.0 and y != 0.0 and (x > 0) == (y > 0))
    judged = len(xs) - zero
    out = {"항목수": len(xs), "rho": rho, "방향일치수": agree, "방향판정대상": judged,
           "방향일치율": agree / judged if judged else None, "델타0_제외수": zero,
           "BotSim주목수": sum(1 for k in base if base[k]["주목"]),
           "주목추적": {"유지": track["유지"], "역방향": track["역방향"], "약화": track["약화"],
                    "기타": sum(v for t, v in track.items() if t not in ("유지", "역방향", "약화"))},
           "fox8주목수": sum(1 for _, r in rows if r["주목"])}
    if with_items:
        out["항목"] = items
    return out


