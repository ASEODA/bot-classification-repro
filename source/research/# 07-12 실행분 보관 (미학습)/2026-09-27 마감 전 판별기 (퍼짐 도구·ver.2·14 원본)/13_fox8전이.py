def residual_scale(R):
    """
    (v1.3 3단계) 척도 s_j = 두 집단 전 계정 |r_ij|의 중앙값(결측 제외). 잔차가 이미
    자기 중심 기준이라 여기서는 라벨을 다시 쓰지 않는다.

    ■ 왜 척도로 나누나 ■
    F 사용률은 0~0.2, R의 문장당 토큰수는 5~40이다. 그대로 평균 내면 눈금이 큰
    자질이 블록 거리를 차지한다. v1.1은 백분위로 눈금을 맞췄다. v1.3은 자질마다
    잔차 크기의 대표값 하나로 나눈다. 나누는 값이 두 집단 공통이라 집단 간 폭의
    비는 그대로 남는다. 중앙값을 쓰는 이유는 중심과 같다. 꼬리의 몇 계정에
    끌려가지 않는다.

    ■ 대체와 제외 ■
    희소 자질은 절반 넘는 계정의 잔차가 0이라 |r|의 중앙값이 0이 된다. 그때는
    |r|의 평균을 쓴다. 평균도 0이면(모든 계정이 자기 중심과 같은 값) 거리에 줄
    정보가 없으므로 뺀다. 정의된 값이 2개 미만인 자질도 뺀다.

    반환: (s, 종류 목록). 종류는 "중앙값" · "평균" · "제외_0" · "제외_정의2미만".
          제외 자질의 s는 nan이다.
    """
    A = np.abs(R)
    med, mean = nanmedian_cols(A), nanmean_cols(A)
    n_def = (~np.isnan(A)).sum(axis=0)
    s = np.full(R.shape[1], np.nan)
    kind = []
    for j in range(R.shape[1]):
        if n_def[j] < 2:
            kind.append("제외_정의2미만")
        elif med[j] > 0:
            s[j] = med[j]
            kind.append("중앙값")
        elif mean[j] > 0:
            s[j] = mean[j]
            kind.append("평균")
        else:
            kind.append("제외_0")
    return s, kind


