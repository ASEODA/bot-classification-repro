def residuals(X, is_bot, c_bot, c_hum):
    """
    (v1.3 3단계) 잔차 r_ij = x_ij − c_gj. 계정마다 자기 집단 중심을 뺀다. 결측은 결측.

    ■ 왜 이것으로 이동 불변이 정확해지나 ■
    한 집단의 원값에 상수 k를 더하면 그 집단 중앙값도 정확히 k만큼 움직인다.
    그래서 뺄셈 결과(잔차)는 그대로다. 자질마다 다른 k여도 같다. v1.2는 이 뒤에
    두 집단을 합쳐 순위를 매겼는데, 순위는 동점 구조에 민감해서 이 성질이 거리
    단계까지 가지 못했다. v1.3은 잔차를 순위로 바꾸지 않는다. 뒤 단계(척도·z·
    거리)는 잔차만 읽으므로 이동 불변이 끝까지 간다.
    """
    C = np.where(is_bot[:, None], c_bot[None, :], c_hum[None, :])
    return X - C


