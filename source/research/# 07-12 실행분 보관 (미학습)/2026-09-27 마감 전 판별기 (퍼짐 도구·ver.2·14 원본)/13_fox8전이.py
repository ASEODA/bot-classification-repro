def spearman(xs, ys):
    """
    Spearman 순위상관. 두 벡터에 각각 순위를 매기고 순위끼리 피어슨을 낸다.
    [11에서 가져옴]
    """
    if len(xs) < 3 or len(xs) != len(ys):
        return None
    rx, _ = ranks_with_ties(xs)
    ry, _ = ranks_with_ties(ys)
    return pearson(rx, ry)


