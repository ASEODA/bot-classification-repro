def apply_detector(bundle, w, X):
    """
    번들 하나를 12-3과 똑같이 적용한다: fit_from_bundle → score(11 score_all, 채점 묶음 = X 전체).
    번들 설명의 손 공식(위치 = 시그모이드, 퍼짐 = d_h − d_b)과도 대조한다.
    """
    fit = fit_from_bundle(bundle)
    sc = score(fit, w, X)
    P = apply_prep(fit["prep"], X)
    s_manual = sigmoid(bundle["intercept"] + P @ np.asarray(bundle["coef"]))
    d_b, d_h = spread_dist(fit["spread"], P)
    chk = {"위치_손공식_최대차": float(np.max(np.abs(s_manual - sc[ROW_POS]))),
           "퍼짐_손공식_최대차": float(np.max(np.abs((d_h - d_b) - sc[ROW_SPREAD])))}
    return sc, P, (d_b, d_h), chk


def auc_boot(s, bidx, hidx, Wb, Wh):
    """점추정 AUC와 재추출 분포(12-3 cmp_matrix · boot_auc). 점추정은 roc_auc_score와 대조."""
    C = cmp_matrix(s[bidx], s[hidx])
    pt = float(C.mean())
    ref = roc_auc_score(np.r_[np.ones(len(bidx)), np.zeros(len(hidx))], np.r_[s[bidx], s[hidx]])
    check(abs(pt - ref) < 1e-12, "비교 행렬 AUC ≠ roc_auc_score")
    return pt, boot_auc(C, Wb, Wh)


def paired_diff(pa, da, pb, db):
    """짝지은 부트스트랩 차 A − B. 두 AUC가 모두 CEILING 이상이면 천장 동률(D16)."""
    lo, hi = ci95(da - db)
    return {"차": pa - pb, "CI95": [lo, hi], "천장동률": bool(pa >= CEILING and pb >= CEILING),
            "하한>0": bool(lo > 0), "상한<0": bool(hi < 0), "0포함": bool(lo <= 0 <= hi)}


def direct_block(s, y, t):
    """직접 전이 지표(11 metrics) + 정확도 + 순도."""
    m = metrics(s, y, t)
    c = m["혼동"]
    m["정확도"] = (c["TP"] + c["TN"]) / len(y)
    m.update(purity(c))
    m["문턱"] = t
    m["봇표시비율"] = float(np.mean(s >= t))      # 기술 칸(D27): 점수 ≥ 문턱인 계정 비율, 판정에 쓰지 않는다
    return m


def adapt_thresholds(scores, y, fold_of, k=N_FOLDS_ADAPT):
    """
    [라벨 사용] 문턱 적응(D17). 겹 f의 문턱은 f 밖 네 겹의 점수와 라벨만으로 고른다.
    평가 겹 f의 라벨은 이 함수 안에서 한 번도 읽지 않는다(관문 E가 교란으로 확인한다).
    반환: [(문턱, 학습 겹 균형정확도)] × k
    """
    out = []
    for f in range(k):
        tr = np.where(fold_of != f)[0]
        out.append(choose_threshold(scores[tr], y[tr]))
    return out


METRIC_KEYS = ("균형정확도", "봇탐지율", "사람오탐률", "F1", "문턱위_봇순도", "문턱아래_사람순도")


def adapt_block(scores, y, fold_of, thr, subset=None, k=N_FOLDS_ADAPT):
    """
    적응 문턱으로 평가한다. subset(불리언)을 주면 평가를 그 부분집합으로 좁힌다(엄격 117).
    주 값 = 겹 평균, 병기 = 모은 OOF.
    """
    mask = np.ones(len(y), dtype=bool) if subset is None else subset
    folds, pred = [], np.zeros(len(y), dtype=bool)
    for f in range(k):
        te = np.where((fold_of == f) & mask)[0]
        t, ba_tr = thr[f]
        pred[te] = scores[te] >= t
        yt = y[te]
        if te.size == 0 or yt.min() == yt.max():
            folds.append({"fold": f, "평가n": int(te.size), "문턱": t, "학습_균형정확도": ba_tr,
                          "평가": None, "사유": "평가 겹에 한 무리만 있다"})
            continue
        m = metrics(scores[te], yt, t)
        m.update(purity(m["혼동"]))
        folds.append({"fold": f, "평가n": int(te.size), "평가_봇": int(yt.sum()), "문턱": t,
                      "학습_균형정확도": ba_tr, "평가": m})
    ev = [fd["평가"] for fd in folds if fd["평가"] is not None]
    mean, sd, n_def = {}, {}, {}
    for key in METRIC_KEYS:
        vals = [e[key] for e in ev if e.get(key) is not None]
        n_def[key] = len(vals)
        mean[key] = float(np.mean(vals)) if vals else None
        sd[key] = float(np.std(vals, ddof=1)) if len(vals) > 1 else None
    idx = np.where(mask)[0]
    yy, pp = y[idx], pred[idx]
    tp = int(np.sum(pp & (yy == 1))); fn = int(np.sum(~pp & (yy == 1)))
    fp = int(np.sum(pp & (yy == 0))); tn = int(np.sum(~pp & (yy == 0)))
    conf = {"TP": tp, "FN": fn, "FP": fp, "TN": tn}
    oof = {"균형정확도": balanced_accuracy(tp, fn, fp, tn) if (tp + fn) and (tn + fp) else None,
           "봇탐지율": tp / (tp + fn) if (tp + fn) else None, "사람오탐률": fp / (fp + tn) if (fp + tn) else None,
           "F1": (2 * tp / (2 * tp + fp + fn)) if (2 * tp + fp + fn) else 0.0,
           "정확도": (tp + tn) / len(idx), "혼동": conf, **purity(conf)}
    return {"겹평균": mean, "겹표준편차": sd, "겹평균_정의된겹수": n_def, "OOF": oof, "fold별": folds}


def five_q(v):
    """다섯 수 요약 + 평균에 오분위수(20 · 40 · 60 · 80 백분위)를 더한다(D28, v3.1 '5분위')."""
    out = five(v)
    v = np.asarray(v, dtype=float)
    v = v[~np.isnan(v)]
    if v.size:
        for q, x in zip((20, 40, 60, 80), np.percentile(v, [20, 40, 60, 80])):
            out[f"P{q}"] = float(x)
    return out


def distance_diag(d_b, d_h, y):
    """[라벨 사용] d_B · d_H를 fox8 봇 · 사람으로 나눠 다섯 수 요약 + 오분위수(D19 · D28)."""
    out = {}
    for name, g in (("봇", y == 1), ("사람", y == 0)):
        out[name] = {"d_B": five_q(d_b[g]), "d_H": five_q(d_h[g]),
                     "d_B<d_H_비율": float(np.mean(d_b[g] < d_h[g])) if g.any() else None}
    return out


def out_of_range_cells(bundle, X, y):
    """12-3 D22 규칙: 결측 아닌 원값 칸 가운데 번들 분위 함수 범위 밖이라 0 · 1로 잘린 칸 비율."""
    xp = bundle["percentile_xp"]
    lo = np.array([x[0] for x in xp])
    hi = np.array([x[-1] for x in xp])
    eff = np.array([len(x) > 1 for x in xp])
    blocks = np.array([b for b, _ in bundle["feature_order"]])
    out = {}
    for name, M in (("봇", X[y == 1]), ("사람", X[y == 0])):
        ok = ~np.isnan(M) & eff[None, :]
        below = np.zeros(M.shape, dtype=bool)
        above = np.zeros(M.shape, dtype=bool)
        below[ok] = (M < lo[None, :])[ok]
        above[ok] = (M > hi[None, :])[ok]
        n = int(ok.sum())
        out[name] = {"칸수": n, "전체": float((below | above).sum() / n) if n else None,
                     "0으로": float(below.sum() / n) if n else None, "1로": float(above.sum() / n) if n else None,
                     "블록별": {bl: (float((below | above)[:, blocks == bl].sum() / ok[:, blocks == bl].sum())
                                  if ok[:, blocks == bl].sum() else None) for bl in BLOCK_SIZES}}
    return out


