def b_distances(XB_b, is_bot):
    """10 v1.3 2~4단계 한 블록: 중심 → 잔차 → 척도 → z(상한 CAP) → 거리."""
    cb, ch = centers(XB_b, is_bot)
    R = residuals(XB_b, is_bot, cb, ch)
    s, kind = residual_scale(R)
    Z = scaled_residuals(R, s)
    with np.errstate(invalid="ignore"):
        over = np.abs(R) / s[None, :] > CAP
    d, used = block_distances(Z)
    return {"cb": cb, "ch": ch, "s": s, "kind": kind, "Z": Z, "over": over, "d": d, "used": used}


