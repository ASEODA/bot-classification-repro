def presence_in(ratios, uids, fam, keys):
    """비교 표본 안의 출현 계정 수(희소 표시용). F · M · UPOS는 값 > 0, R은 정의된 수."""
    s = set(uids)
    if fam == "R":
        return {k: sum(1 for u in s if ratios[u][k] is not None) for k in keys}
    return {k: sum(1 for u in s if (ratios[u][k] or 0) > 0) for k in keys}


