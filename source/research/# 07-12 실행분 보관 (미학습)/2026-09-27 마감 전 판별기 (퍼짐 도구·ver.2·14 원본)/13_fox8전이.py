def result_digest(out):
    """실행 시각 · 경로 · 소요초를 뺀 결과의 sha256(D22). 프로세스 사이 결정성 대조용."""
    keep = {k: out[k] for k in ("관문_요약", "단서", "엄격117", "시험a_차이전이", "시험b_동질성전이",
                                "시험c_판별기전이", "예측대조", "주장수위표_v3")}
    return hashlib.sha256(json.dumps(jsonable(keep), sort_keys=True, ensure_ascii=False).encode("utf-8")).hexdigest()


