def scaled_residuals(R, s):
    """
    (v1.3 4단계) z_ij = min(|r_ij| ÷ s_j, CAP), CAP = 5.

    ■ 왜 상한을 두나 ■
    척도로 나눈 잔차는 긴 꼬리를 그대로 가진다. 한 계정이 어느 자질에서 척도의
    40배쯤 떨어져 있으면 그 한 자질이 그 계정의 블록 거리를 거의 정한다. 상한
    5는 한 자질이 한 계정에 줄 수 있는 몫을 묶는다. 5는 실행 전에 선언한 값이다.
    제외 자질(s가 nan)은 모든 계정에서 결측이 된다.
    """
    with np.errstate(invalid="ignore"):
        return np.minimum(np.abs(R) / s[None, :], CAP)


# ── [10_동질성검정.py (v1.3)] block_distances ──
def block_distances(Z):
    """
    (v1.3 4단계) 계정마다 블록 거리 d_i = 정의된 자질의 z 평균.

    결측 자질(잔차 결측 또는 제외 자질)은 그 계정의 평균에서 뺀다. 그래서
    계정마다 평균 낸 자질 수가 다를 수 있다. 그 수를 함께 돌려준다(v1.1과 같음).
    """
    used = (~np.isnan(Z)).sum(axis=1)
    with np.errstate(invalid="ignore"):
        d = np.nansum(Z, axis=1) / np.where(used > 0, used, np.nan)
    return d, used


# ── [10_동질성검정.py (v1.3)] ratio_of ──
def ratio_of(d_bot, d_hum):
    """비율 = 사람 거리 중앙값 ÷ 봇 거리 중앙값. 1보다 크면 봇이 더 좁다."""
    return float(np.median(d_hum)) / float(np.median(d_bot))


# ── [10_동질성검정.py (v1.3)] perm_ratios ──
def perm_ratios(d_bot, d_hum, swaps):
    """
    [라벨 사용] 쌍 안 교환. swaps[k, i]가 참이면 k번째 순열에서 쌍 i의 두 거리
    값을 맞바꾼다. 중심은 다시 만들지 않는다 : 4단계 거리 값만 섞는다.
    d_bot[i]와 d_hum[i]는 같은 쌍의 봇·사람이다(순서가 쌍을 뜻한다).
    """
    b = np.where(swaps, d_hum[None, :], d_bot[None, :])
    h = np.where(swaps, d_bot[None, :], d_hum[None, :])
    return np.median(h, axis=1) / np.median(b, axis=1)


# ── [10_동질성검정.py (v1.3)] p_values ──
def p_values(obs, perm):
    """
    단측 p = (순열비율 ≥ 관측비율 횟수 + 1) ÷ (순열 수 + 1)
    양측 p = (|log 순열비율| ≥ |log 관측비율| 횟수 + 1) ÷ (순열 수 + 1)   (결정 I)
    비교에는 상대 허용오차 1e-12를 둔다(결정 H).
    """
    perm = np.asarray(perm, dtype=float)
    ge = int(np.sum(perm >= obs * (1 - REL_TOL)))
    lo = abs(math.log(obs))
    ge2 = int(np.sum(np.abs(np.log(perm)) >= lo * (1 - REL_TOL)))
    n = perm.size
    return (ge + 1) / (n + 1), (ge2 + 1) / (n + 1), ge, ge2


# ── [10_동질성검정.py (v1.3)] exact_p ──
def exact_p(obs, all_ratios):
    """교환을 전부 늘어놓았을 때의 정확 p(+1 없음). 손 예제 전용."""
    r = np.asarray(all_ratios, dtype=float)
    lo = abs(math.log(obs))
    return (float(np.mean(r >= obs * (1 - REL_TOL))),
            float(np.mean(np.abs(np.log(r)) >= lo * (1 - REL_TOL))))


# ── [10_동질성검정.py (v1.3)] hand_run ──
def hand_run(X, is_bot, swaps):
    """
    손 예제 한 벌을 원값부터 p까지 돈다(이동 불변 관문용). 본 계산과 같은 함수를
    같은 순서로 부른다: centers → residuals → residual_scale → scaled_residuals →
    block_distances → ratio_of → perm_ratios → exact_p·p_values.
    반환: (계정별 거리, 관측 비율, 교환별 비율, (정확 단측, 정확 양측, 공식 단측, 공식 양측))
    """
    cb, ch = centers(X, is_bot)
    R = residuals(X, is_bot, cb, ch)
    s, _ = residual_scale(R)
    d, _ = block_distances(scaled_residuals(R, s))
    idx = {u: i for i, u in enumerate(HAND_IDS)}
    d_bot = np.array([d[idx[b]] for b, _ in HAND_PAIRS])
    d_hum = np.array([d[idx[h]] for _, h in HAND_PAIRS])
    obs = ratio_of(d_bot, d_hum)
    got = perm_ratios(d_bot, d_hum, swaps)
    e1, e2 = exact_p(obs, got)
    f1, f2, _, _ = p_values(obs, got)
    return d, obs, got, (e1, e2, f1, f2)


