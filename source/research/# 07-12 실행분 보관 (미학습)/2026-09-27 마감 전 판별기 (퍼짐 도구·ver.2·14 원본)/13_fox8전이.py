def close(a, b, tol=HAND_TOL):
    """손 예제 대조. 계산값 nan(결측)은 기대값 None과 같은 것으로 본다."""
    if a is not None and math.isnan(float(a)):
        a = None
    if a is None or b is None:
        return a is None and b is None
    return abs(float(a) - float(b)) <= tol


