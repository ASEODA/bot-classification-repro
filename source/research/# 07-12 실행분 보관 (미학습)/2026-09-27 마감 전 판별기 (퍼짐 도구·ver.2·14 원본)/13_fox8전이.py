def boot_auc(C, Wb, Wh):
    """재추출마다의 AUC = 뽑힌 횟수로 가중한 비교 행렬 평균."""
    return ((Wb @ C) * Wh).sum(axis=1) / (Wb.sum(axis=1) * Wh.sum(axis=1))


