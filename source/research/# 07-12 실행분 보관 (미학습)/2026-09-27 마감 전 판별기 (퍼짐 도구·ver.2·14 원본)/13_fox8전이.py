def cmp_matrix(sb, sh):
    """봇 × 사람 비교 행렬: 봇 점수가 크면 1, 같으면 0.5, 작으면 0. 평균이 곧 AUC다."""
    return (sb[:, None] > sh[None, :]).astype(float) + 0.5 * (sb[:, None] == sh[None, :])


