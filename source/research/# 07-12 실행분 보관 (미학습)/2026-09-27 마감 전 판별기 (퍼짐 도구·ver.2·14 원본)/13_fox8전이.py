def nanmedian_cols(M):
    """열별 중앙값. 한 열이 통째로 nan이면 nan (numpy 경고 없이)."""
    out = np.full(M.shape[1], np.nan)
    for j in range(M.shape[1]):
        v = M[:, j]
        v = v[~np.isnan(v)]
        if v.size:
            out[j] = np.median(v)
    return out


