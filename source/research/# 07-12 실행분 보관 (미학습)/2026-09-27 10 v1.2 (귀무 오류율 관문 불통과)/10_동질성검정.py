def center_groups(X, is_bot):
    """
    [라벨 사용] 결정 B2 중심 정렬(v1.2). 백분위 직전에 자질마다, 집단마다 결측을
    뺀 원값 중앙값을 그 집단 계정의 원값에서 뺀다. 계산에 라벨을 쓰는 첫 자리다.

    ■ 왜 필요한가 : v1.1이 10-1 관문에서 걸린 이유 ■
    v1.1은 "자기 집단 중심까지의 거리라서 위치 차이가 들어오지 않는다"고 보았다.
    그런데 중심과 거리는 백분위 공간에서 잰다. 두 집단을 합쳐 매긴 평균순위
    백분위는 원값을 곡선으로 구부린다. 0 근처에 몰리고 꼬리가 긴 사용률처럼
    원값이 치우친 자질에서 한 집단을 통째로 위로 옮기면, 그 집단은 백분위가
    넓게 벌어지는 쪽으로 가고 다른 집단은 좁게 눌리는 쪽에 남는다. 원값의 폭이
    같아도 백분위 공간의 폭은 달라진다. 모의 점검에서 순수한 위치 이동의 비율이
    대칭 자료 1.00, 오른쪽 치우침 1.29, 왼쪽 치우침 0.77이었다. 10-1 모의 B(가짜
    봇 + MAD)의 거짓 유의율은 F 1.00, M 0.97, R 0.54였다.

    ■ 어떻게 푸나 ■
    곡선을 지나기 전에 위치를 지운다. 두 집단의 원값 중앙값을 각각 0으로 맞춘
    뒤 합쳐서 순위를 매긴다. 그러면 한 집단의 원값에 상수를 더해도 정렬 뒤 값이
    그대로라 백분위·거리·비율·p가 바뀌지 않는다(관문 1의 이동 불변).
    평균이 아니라 중앙값을 빼는 이유는 중심을 중앙값으로 잡는 이유와 같다.
    꼬리의 몇 계정에 끌려가지 않는다.

    ■ 무엇을 버리나 ■
    집단 간 위치 정보를 버린다. 10은 산포만 묻고, 위치는 06~09가 이미 쟀다.
    정렬은 더하기 꼴의 차이만 지운다. 두 집단의 분포 모양이 다르면 그 차이는
    백분위 폭에 남는다.

    ■ 정의된 값이 2개 미만인 집단 ■
    그 자질에서 그 집단은 빼지 않고 원값 그대로 둔다. 값 하나의 중앙값은 그 값
    자신이라, 빼면 그 계정이 저절로 0이 된다. 결측은 결측으로 남는다. 몇 칸인지
    표시를 돌려준다(v1.1이 정의 2개 미만을 따로 센 것과 같은 취지).

    반환: (정렬된 행렬, 봇 원값 중앙값, 사람 원값 중앙값, 봇 정렬 제외 표시,
           사람 정렬 제외 표시). 정렬하지 않은 자질의 중앙값 자리는 nan이다.
    """
    Xc = np.array(X, dtype=float)
    meds, skips = [], []
    for grp in (is_bot, ~is_bot):
        G = Xc[grp]
        few = (~np.isnan(G)).sum(axis=0) < 2
        m = nanmedian_cols(G)
        Xc[grp] = G - np.where(few, 0.0, m)[None, :]
        meds.append(np.where(few, np.nan, m))
        skips.append(few)
    return Xc, meds[0], meds[1], skips[0], skips[1]


def percentile_column(col):
    """
    자질 하나의 값 목록(결측은 nan)을 순위 백분위로 바꾼다. 라벨은 쓰지 않는다.

        백분위 = (평균순위 − 1) ÷ (정의된 계정 수 − 1)      (결정 B)

    ■ 왜 평균순위인가 ■
    F 자질은 0이 많다. 절반 넘는 계정이 어떤 단어를 한 번도 안 쓰면 그 계정들은
    전부 같은 값이다. 동점에 임의 순서를 주면 같은 값의 계정들이 서로 다른
    백분위를 받아 가짜 산포가 생긴다. 평균순위를 주면 같은 값은 같은 백분위다.

    ■ 결측 ■
    결측 계정은 순위에 넣지 않고 nan으로 남긴다. 결측을 0이나 중앙으로 채우면
    "잴 거리가 없다"가 "값이 이렇다"로 둔갑한다.
    """
    col = np.asarray(col, dtype=float)
    out = np.full(col.shape, np.nan)
    ok = ~np.isnan(col)
    v = col[ok]
    n = v.size
    if n < 2:
        return out, n
    order = np.argsort(v, kind="mergesort")
    sv = v[order]
    ranks = np.empty(n)
    i = 0
    while i < n:
        j = i + 1
        while j < n and sv[j] == sv[i]:
            j += 1
        ranks[order[i:j]] = (i + 1 + j) / 2.0      # 순위 i+1 … j 의 평균
        i = j
    out[ok] = (ranks - 1.0) / (n - 1.0)
    return out, n


def percentile_matrix(X):
    """계정 × 자질 행렬 전체를 열마다 백분위로. 정의된 계정 수도 돌려준다."""
    P = np.full(X.shape, np.nan)
    n_def = []
    for j in range(X.shape[1]):
        P[:, j], n = percentile_column(X[:, j])
        n_def.append(n)
    return P, n_def


def nanmedian_cols(M):
    """열별 중앙값. 한 열이 통째로 nan이면 nan (numpy 경고 없이)."""
    out = np.full(M.shape[1], np.nan)
    for j in range(M.shape[1]):
        v = M[:, j]
        v = v[~np.isnan(v)]
        if v.size:
            out[j] = np.median(v)
    return out


def centers(P, is_bot):
    """[라벨 사용] 집단별 자질 중앙값(백분위 공간). v1.2에서는 center_groups(결정 B2)가 먼저 라벨을 쓰고, 이 함수는 두 번째다."""
    return nanmedian_cols(P[is_bot]), nanmedian_cols(P[~is_bot])


def block_distances(P, is_bot, c_bot, c_hum):
    """
    계정마다 자기 집단 중심까지의 블록 거리 = |백분위 − 중심|의 평균.

    결측 자질(백분위 nan 또는 중심 nan)은 그 계정의 평균에서 뺀다. 그래서
    계정마다 평균 낸 자질 수가 다를 수 있다. 그 수를 함께 돌려준다.
    """
    C = np.where(is_bot[:, None], c_bot[None, :], c_hum[None, :])
    A = np.abs(P - C)
    used = (~np.isnan(A)).sum(axis=1)
    with np.errstate(invalid="ignore"):
        d = np.nansum(A, axis=1) / np.where(used > 0, used, np.nan)
    return d, used


def ratio_of(d_bot, d_hum):
    """비율 = 사람 거리 중앙값 ÷ 봇 거리 중앙값. 1보다 크면 봇이 더 좁다."""
    return float(np.median(d_hum)) / float(np.median(d_bot))


def perm_ratios(d_bot, d_hum, swaps):
    """
    [라벨 사용] 쌍 안 교환. swaps[k, i]가 참이면 k번째 순열에서 쌍 i의 두 거리
    값을 맞바꾼다. 중심은 다시 만들지 않는다 : 4단계 거리 값만 섞는다.
    d_bot[i]와 d_hum[i]는 같은 쌍의 봇·사람이다(순서가 쌍을 뜻한다).
    """
    b = np.where(swaps, d_hum[None, :], d_bot[None, :])
    h = np.where(swaps, d_bot[None, :], d_hum[None, :])
    return np.median(h, axis=1) / np.median(b, axis=1)


def p_values(obs, perm):
    """
    단측 p = (순열비율 ≥ 관측비율 횟수 + 1) ÷ (순열 수 + 1)
    양측 p = (|log 순열비율| ≥ |log 관측비율| 횟수 + 1) ÷ (순열 수 + 1)   (결정 I)
    비교에는 상대 허용오차 1e-12를 둔다(결정 H).
    """
    perm = np.asarray(perm, dtype=float)
    ge = int(np.sum(perm >= obs * (1 - REL_TOL)))
    lo = abs(math.log(obs))
    ge2 = int(np.sum(np.abs(np.log(perm)) >= lo * (1 - REL_TOL)))
    n = perm.size
    return (ge + 1) / (n + 1), (ge2 + 1) / (n + 1), ge, ge2


def exact_p(obs, all_ratios):
    """교환을 전부 늘어놓았을 때의 정확 p(+1 없음). 손 예제 전용."""
    r = np.asarray(all_ratios, dtype=float)
    lo = abs(math.log(obs))
    return (float(np.mean(r >= obs * (1 - REL_TOL))),
            float(np.mean(np.abs(np.log(r)) >= lo * (1 - REL_TOL))))


def five(v):
    v = np.asarray(v, dtype=float)
    v = v[~np.isnan(v)]
    q1, q2, q3 = np.percentile(v, [25, 50, 75])
    return {"n": int(v.size), "최소": float(v.min()), "Q1": float(q1),
            "중앙": float(q2), "Q3": float(q3), "최대": float(v.max()),
            "평균": float(v.mean())}


