# [자질 행렬] F·M·R 원값 (라벨 없음)
# ════════════════════════════════════════════════════════════════════════
def build_blocks(acc_all, acc1, ids, words, rates):
    """
    1,024계정의 F·M·R 원값 행렬을 만든다. 행 순서는 ids(봇 512 → 사람 512,
    쌍 순서)다. 이 순서는 나중에 쌍을 맞추는 데만 쓰고, 백분위는 순서와 무관하다.
    """
    # F : 05 규칙 사용률(6자리 반올림), 없는 단어는 0.0 (dense_vectors와 같은 규율)
    XF = np.array(dense_vectors(ids, rates, words), dtype=float)

    # M : 07 규칙. 축 분류는 04 전체 1,869계정에서 유도(결정 E).
    axis_map = build_axis_map(acc_all)
    feat_keys = sorted({k for a in acc_all.values() for k in a.get("자질", {})})
    upos_keys = sorted({k for a in acc_all.values() for k in a.get("UPOS", {})})
    sub = {u: acc_all[u] for u in ids}
    mr, _, _ = compute_ratios(sub, feat_keys, axis_map)
    ur, _ = compute_upos_ratios(sub, upos_keys)
    m_keys = feat_keys + upos_keys
    XM = np.array([[np.nan if mr[u][k] is None else mr[u][k] for k in feat_keys]
                   + [np.nan if ur[u][k] is None else ur[u][k] for k in upos_keys]
                   for u in ids], dtype=float)

    # R : 08 규칙. 문장길이 목록은 04-1에서 붙인다.
    rsub = {u: {**acc_all[u], "문장길이": acc1[u]["문장길이"]} for u in ids}
    rr = compute_features(rsub)
    XR = np.array([[np.nan if rr[u][k] is None else rr[u][k] for k in RKEYS]
                   for u in ids], dtype=float)

    kinds = {k: denom_kind_of(k, axis_map) for k in feat_keys}
    return ({"F": XF, "M": XM, "R": XR},
            {"F": list(words), "M": m_keys, "R": list(RKEYS)},
            axis_map, feat_keys, upos_keys, kinds)


